    private void load_stepinput(String ccode,String spk,String step){
        sql="select * from (\n" +
            "	select a.id,a.ccode,a.cnbkt,a.dtran,a.ctype,a.cnbkt_po,c.cplot,d.cname as operator,a.cstep_name,\n" +
            "	case when a.cgood_unit='LEMBAR' then convert(varchar,a.cgood)+ ' Lembar ('+convert(varchar,a.cgood*c.cplot)+' Pcs)' else convert(varchar,a.cgood)+' Pcs' end as good,\n" +
            "	case when a.cwaste_unit='LEMBAR' then convert(varchar,a.cwaste)+ ' Lembar ('+convert(varchar,a.cwaste*c.cplot)+' Pcs)' else convert(varchar,a.cwaste)+' Pcs' end as waste\n" +
            "	from PProdSteps a\n" +
            "	join PWorkOrder b on a.ccode=b.ccode and a.cnbkt=b.cnbkt\n" +
            "	join BOMProduct c on b.cnbkt_bom=c.cnbkt\n" +
            "	join MKaryawan d on a.cnik=d.nik \n" +
            "\n" +
            "	union all\n" +
            "\n" +
            "	select a.id,a.ccode,a.cworkorder as cnbkt,a.dtran,0 as ctype,'' as cnbkt_po,0 as cplot,d.cname as operator,'PACKAGING'  as cstep_name,\n" +
            "	convert(nvarchar,a.nqty_small*a.nqty_box)+' Pcs' as good,'0 Pcs' as waste\n" +
            "	From PBoxPacking a --join PBoxPackingD b on a.ccode=b.ccode and a.cnbkt=b.cnbkt\n" +
            "	join (select a.*,b.cplot from PWorkOrder a join BOMProduct b on a.cnbkt_bom=b.cnbkt) c on a.ccode=c.ccode and a.cworkorder=c.cnbkt\n" +
            "	left join mkaryawan d on a.cnik=d.nik \n" +
            "	join MProduk e on c.cgroup=e.cgroup and c.cproduct=e.cproduct\n" +
            ") a \n" +
            "where a.ccode='"+ccode+"' and a.cnbkt='"+spk+"' and a.cstep_name = '"+step+"' \n"+
            "order by a.dtran desc";
        System.out.println(sql);
        rs = con.queryResult(sql);
        rfa.clear_table(MenuAdmin.keyssDef, jTable3);
        DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
        try {
            while(rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id"),
                    rfa.DateString(keyssDef,rs.getDate("dtran"),"dd/MM/yyyy"),
                    rs.getString("operator"),
                    rs.getString("good"),
                    rs.getString("waste"),
                    rs.getString("ctype"),
                    rs.getString("cnbkt_po"),
                });
            }
        } catch (SQLException ex) {
            Logger.getLogger(ProduksiInput2.class.getName()).log(Level.SEVERE, null, ex);
        }
        con.resizeColumnWidth(jTable3);
    } 
    
