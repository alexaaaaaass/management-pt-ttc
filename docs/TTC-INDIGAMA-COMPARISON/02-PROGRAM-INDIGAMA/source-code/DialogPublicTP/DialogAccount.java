    private void loadData(){
        String where="";
        if(!ctype.isEmpty() || !ctype.equalsIgnoreCase("")) {
            where+=" and fAccount in ("+ctype+") ";
        }
        sql = "select * from maccount where caccnt like '%"+tkodes.getText()+"%' and cdesc like '%"+tnamas.getText()+"%' "+where
                + " order by caccnt,cdesc ";
        rs = con.queryResult(sql);
        rfa.clear_table(MenuAdmin.keyssDef, jTable3);
        DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
        try {
            while(rs.next()){
                String st = "Tidak Aktif";
                if(rs.getString("fstatus").equals("1")) {
                    st = "Aktif";
                }
                model.addRow(new Object[]{
                    rs.getString("id"),rs.getString("caccnt"),rs.getString("cdesc"),rs.getString("fAccount"),
                    rs.getString("cPeriod"),
                    rs.getDouble("NDebet"),rs.getDouble("NCredit"),st
                });
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }
    

