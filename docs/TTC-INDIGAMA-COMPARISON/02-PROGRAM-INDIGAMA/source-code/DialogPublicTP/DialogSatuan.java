    private void listData(){
        
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.getDataVector().removeAllElements();

        
        jTable1.getTableHeader().setEnabled(false);
        sql =   "select a.*,isnull(b.cname,'') as terkecil,case when isnull(a.namasatuan,'') = '' then a.cname else a.namasatuan end as namanya from msatuan a left join msatuan b on a.id_turunan=b.id\n" +
                "order by a.cname ";
        
        if(units.length() >0) {
            String[] satuan = new String[10];
            satuan[0]="(select id from MSatuan where cname = '"+units+"')";
            String sqll="";
            for(int i=1; i<=9; i++){
                satuan[i]="(select id from MSatuan where id_turunan in "+satuan[i-1]+")";
                sqll+=satuan[i].substring(1,satuan[i].length()-1);
                if(i<9) { sqll+="\n union \n"; }

            }
            sql =   "select a.*,isnull(b.cname,'') as terkecil,case when isnull(a.namasatuan,'') = '' then a.cname else a.namasatuan end as namanya from msatuan a left join msatuan b on a.id_turunan=b.id\n" +
                    "where a.cname = '"+units+"' or a.id in ("+sqll+")   \n"+
                "order by a.cname,a.small_value ";
            
        }
        System.out.println(sql);
        rs=con.queryResult(sql);
        int no=1;
        try {
            while(rs.next()){
                String strMain = rs.getString("namanya");
                String[] arrSplit = strMain.split(" ");
    
                model.addRow(new Object[]{
                    no++,
                    rs.getString("cname"),arrSplit[0],rs.getDouble("big_value"),rs.getDouble("small_value"),rs.getString("id"),rs.getString("terkecil")
                });
            }
        } catch (SQLException ex) {
            Logger.getLogger(DialogSatuan.class.getName()).log(Level.SEVERE, null, ex);
        }
       
    }
    
