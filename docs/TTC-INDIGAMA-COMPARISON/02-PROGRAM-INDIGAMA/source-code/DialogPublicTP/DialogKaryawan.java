    private void listData(){
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.getDataVector().removeAllElements();
        jTable1.removeAll();
        
        sql = "select a.nik,a.cname,b.cjabatan as nama_jabatan,a.cborongan,c.cname as gudang "
                + " from mkaryawan a left join mjabatan b on a.cjabatan = b.id_jab\n" +
                " join mgudang c on a.ccode=c.ccode"+
                    " where a.ccode='"+tcodes.getText()+"' ";
    
        rs = con.queryResult(sql);
        nomor = 1;
        try {
            while(rs.next()){
                String borongan = "";
                if(rs.getString("cborongan").equals("1")) {
                    borongan = "Borongan";
                }
                model.addRow(new Object[]{rs.getString("nik").toString(),rs.getString("cname").toString().toUpperCase(),rs.getString("nama_jabatan"),
                    borongan,
                    rs.getString("gudang")
                });
            }
        } catch (SQLException ex) {
            Logger.getLogger(DialogKaryawan.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        
    }

