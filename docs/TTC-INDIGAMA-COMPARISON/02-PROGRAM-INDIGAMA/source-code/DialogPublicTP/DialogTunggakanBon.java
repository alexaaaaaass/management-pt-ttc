    private void liatTagihan() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.getDataVector().removeAllElements();
        jTable1.removeAll();
        
        
        sql =   "select distinct a.cnbkt,a.id_member,a.dtran,a.total,a.kembali,b.lamatempo,b.akhirtempo as akhirtempo, \n" +
                "a.total - (a.bayar+(select isnull(sum(cicilan),0) from TranSaleBonPay where cnbkt = a.cnbkt)) as SisaCicilan,c.cname \n" +
                "from TranSale a left join TranSaleBon b on a.cnbkt = b.cnbkt join MCustomer c on a.id_member = c.kode_customer       \n" +
                "and a.total - (a.bayar+(select isnull(sum(cicilan),0) from TranSaleBonPay where cnbkt = a.cnbkt)) > 0 \n" +
                "order by a.cnbkt desc";
        
        sql="select distinct aa.ccode,aa.cname as gudang,a.cnbkt,a.id_member,a.dtran,a.total,a.kembali,b.lamatempo,b.akhirtempo as akhirtempo, \n" +
            "a.total - (a.bayar+isnull(d.cicilan,0)) as SisaCicilan,c.cname \n" +
            "from TranSale a join MGudang aa on a.ccode=aa.ccode\n" +
            "left join TranSaleBon b on a.cnbkt = b.cnbkt and a.ccode=b.ccode\n" +
            "left join (\n" +
            "	select ccode,cnbkt,sum(cicilan) as cicilan from TranSaleBonPay\n" +
            "	group by ccode,cnbkt\n" +
            ") d on a.ccode=d.ccode and a.cnbkt=d.cnbkt\n" +
            "join MCustomer c on a.id_member = c.kode_customer       \n" +
            " --where a.total - (a.bayar+isnull(d.cicilan,0)) > 0 \n" +
            "order by a.cnbkt desc\n" +
            "\n" +
            "";
        System.out.println(sql);
        rs = con.queryResult(sql);
        try {
            while(rs.next()){
                Double SisaCicilan = 0.0;
                if(rs.getString("SisaCicilan") != null) {
                    SisaCicilan = Double.valueOf(rs.getString("SisaCicilan").toString());
                }
                Double total = 0.0;
                if(rs.getString("total") != null) {
                    total = Double.valueOf(rs.getString("total").toString());
                }
                model.addRow(new Object[]{rs.getString("cnbkt"),rs.getString("id_member"),rs.getString("cname").toString().toUpperCase(),rfa.DateString(keyssDef, rs.getDate("dtran"), "dd MMM yyyy"),total,
                SisaCicilan,rs.getString("lamatempo")+" ("+rfa.DateString(keyssDef, rs.getDate("akhirtempo"), "dd MMM yyyy")+")",rs.getString("gudang"),rs.getString("ccode")});
            }
        } catch (SQLException ex) {
            Logger.getLogger(DialogTunggakanBon.class.getName()).log(Level.SEVERE, null, ex);
        }
        TableColumnAdjuster tca = new TableColumnAdjuster(jTable1);
        tca.adjustColumns();
    }

