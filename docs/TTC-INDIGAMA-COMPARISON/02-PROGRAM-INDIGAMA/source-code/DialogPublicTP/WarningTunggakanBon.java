    private void liatTagihan(String member) {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.getDataVector().removeAllElements();
        sql =   "select distinct a.cnbkt,a.id_member,a.dtran,a.total,a.kembali,a.KodeBayar,b.lamatempo,b.akhirtempo, \n" +
                "a.total - (a.bayar+(select isnull(sum(cicilan),0) from TranSaleBonPay where cnbkt = a.cnbkt)) as SisaCicilan,c.cname \n" +
                "from TranSale a inner join TranSaleBon b on a.cnbkt = b.cnbkt join MCustomer c on a.id_member = c.kode_customer \n" +
                "and a.id_member = '"+member+"'\n" +
                "and a.total - (a.bayar+(select isnull(sum(cicilan),0) from TranSaleBonPay where cnbkt = a.cnbkt)) > 0";
        
        sql="select distinct c.cname as name,aa.ccode,aa.cname as gudang,a.cnbkt,a.id_member,a.dtran,a.total,a.kembali,b.lamatempo,b.akhirtempo as akhirtempo, \n" +
            "a.total - (a.bayar+isnull(d.cicilan,0)) as SisaCicilan,c.cname \n" +
            "from TranSale a join MGudang aa on a.ccode=aa.ccode\n" +
            "left join TranSaleBon b on a.cnbkt = b.cnbkt and a.ccode=b.ccode\n" +
            "left join (\n" +
            "	select ccode,cnbkt,sum(cicilan) as cicilan from TranSaleBonPay\n" +
            "	group by ccode,cnbkt\n" +
            ") d on a.ccode=d.ccode and a.cnbkt=d.cnbkt\n" +
            "join MCustomer c on a.id_member = c.kode_customer       \n" +
            "where a.id_member = '"+member+"' and a.total - (a.bayar+isnull(d.cicilan,0)) > 0 \n" +
            "order by a.cnbkt desc\n" +
            "\n" +
            "";
        rs = con.queryResult(sql.toLowerCase());
        Double totalKredit=0.0;
        try {
            while(rs.next()){
                Double total = 0.0;
                if(rs.getString("total") != null) {
                    total = Double.valueOf(rs.getString("total").toString());
                }
                Double SisaCicilan = 0.0;
                if(rs.getString("sisacicilan") != null) {
                    SisaCicilan = Double.valueOf(rs.getString("sisacicilan").toString());
                    totalKredit+=rs.getDouble("sisacicilan");
                }
                jLabel1.setText("Member Atas Nama "+rs.getString("name")+" ("+member+") Belum Melunasi Pembayaran dengan detail");
                model.addRow(new Object[]{rs.getString("cnbkt"),rfa.DateString(keyssDef, rs.getDate("dtran"), "dd MMM yyyy"),total,
                SisaCicilan,rs.getString("lamatempo")+" ("+rfa.DateString(keyssDef, rs.getDate("akhirtempo"), "dd MMM yyyy")+")"});
            }
        } catch (SQLException ex) {
            Logger.getLogger(WarningTunggakanBon.class.getName()).log(Level.SEVERE, null, ex);
        }
        con.resizeColumnWidth(jTable1);
       jTextField1.setText("Total Tagihan : Rp. "+rfa.formatDecimal1.format(totalKredit));
    }

