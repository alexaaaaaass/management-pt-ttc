    private void loadData(){
        sql="select a.ccode,b.kode,a.spk,a.dtranspk,a.cgroup,a.cproduct,c.cnameProduct,\n" +
            "sum(case when a.kode='PROD' then a.jmlbox else 0 end) as box_prod,\n" +
            "sum(case when a.kode='PROD' then a.totalpcs else 0 end) as qty_prod,\n" +
            "sum(case when a.kode='RETURN' then a.jmlbox else 0 end) as box_return,\n" +
            "sum(case when a.kode='RETURN' then a.totalpcs else 0 end) as qty_return,\n" +
            "sum(case when a.kode='DELIV' then a.jmlbox*-1 else 0 end) as box_kirim,\n" +
            "sum(case when a.kode='DELIV' then a.totalpcs*-1 else 0 end) as qty_kirim\n" +
            "from  ProductStock a join pworkorder b on a.ccode=b.ccode and a.spk=b.cnbkt\n" +
            "--left join MCustomer b on a.kode_customer=b.kode_customer\n" +
            "join MProduk c on a.cgroup=c.cgroup and a.cproduct=c.cproduct\n" +
            "where (a.dtranspk >= '"+rfa.DateString(keyssDef, jDate1.getDate(), "yyyy-MM-dd")+"' and a.dtranspk <= '"+rfa.DateString(keyssDef, jDate2.getDate(), "yyyy-MM-dd")+"')\n";
        //if(!tcustomer.getText().isEmpty()) sql+=" and b.cname like '%"+tcustomer.getText()+"%' ";
        if(!tspk.getText().isEmpty()) sql+=" and a.spk like '%"+tspk.getText()+"%' ";
        if(!tproduk.getText().isEmpty()) sql+=" and c.cnameProduct like '%"+tproduk.getText()+"%' ";
        sql+="group by a.ccode,a.dtranspk,a.spk,a.cgroup,a.cproduct,c.cnameProduct,b.kode\n" +
" order by a.dtranspk desc,a.spk desc";
        
        System.out.println(sql);
        rs = con.queryResult(sql);
        rfa.clear_table(MenuAdmin.keyssDef, jTable1);
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        int nomor=1;
        try {
            while(rs.next()){
                model.addRow(new Object[]{
                    rs.getString("kode"),
                    rs.getString("ccode"),
                    rs.getString("spk"),
                    rfa.DateString(keyssDef, rs.getDate("dtranspk"),"dd/MM/yyyy"), 
                    rs.getString("cnameProduct"),
                    rs.getDouble("box_prod"),
                    rs.getDouble("qty_prod"),
                    rs.getDouble("box_return"),
                    rs.getDouble("qty_return"),
                    rs.getDouble("box_kirim"),
                    rs.getDouble("qty_kirim"),
                    rs.getDouble("box_prod") + rs.getDouble("box_return") - rs.getDouble("box_kirim"),
                    rs.getDouble("qty_prod") + rs.getDouble("qty_return") - rs.getDouble("qty_kirim"),
                    
                });
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
        TableColumnAdjuster tca = new TableColumnAdjuster(jTable1);
        tca.adjustColumns();
        iNama.setText("Total Data : "+rfa.formatDecimal1.format(jTable1.getRowCount()));
    }
    
