    private void loadsatuan(String satuan){
        jListSatuan.removeAll();
        jListSatuan.removeAllItems();
        satuanNilai = new ArrayList<>();
        satuanNilai.clear();
        sql="select cname,big_value as terkecil from MSatuan where cname= '"+satuan+"'\n" +
            "union all\n" +
            "select cname,small_value as terkecil  from MSatuan where id_turunan in (select id from MSatuan where cname= '"+satuan+"')";
        rs = con.queryResult(sql);
        try {
            while(rs.next()){
                jListSatuan.addItem(rs.getString("cname"));
                satuanNilai.add(rs.getInt("terkecil"));
            }
        } catch (SQLException ex) { ex.printStackTrace();}
    }
   
    
    
