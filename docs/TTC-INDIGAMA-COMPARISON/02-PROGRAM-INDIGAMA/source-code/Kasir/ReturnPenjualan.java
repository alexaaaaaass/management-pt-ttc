    private void loadDataKwitansi(){
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.getDataVector().removeAllElements();
        jTable1.removeAll();
        member = ""; diskon_member = 0.0;idjual="";
        bayar=subTotalReturn=subTotalNoReturn=0.0;
        sql =   "select a.cnbkt,a.id_member,a.cgroup,a.cproduct,b.cnameProduct,a.jumlah,a.harga,a.diskon_barang,a.diskon_member,a.total,a.bayar \n" +
                    "from TranSale a left join MProduk b on a.cproduct = b.cproduct \n" +
                "where a.ccode='"+tcodes.getText()+"' and  a.cnbkt = '"+NoKwt.getText().trim()+"'  and left(cnbkt,1) <> 'R' ";
        rs = con.queryResult(sql.toLowerCase());
        try {
            while(rs.next()){
                model.addRow(new Object[]{rs.getString("cnbkt"),rs.getString("cproduct"),
                    rs.getString("cnameProduct"),rs.getDouble("jumlah"),
                    rs.getDouble("harga"),rs.getDouble("diskon_barang"),
                    rs.getDouble("total"),
                    rs.getString("cgroup")});
                
                member = rs.getString(("id_member"));
                diskon_member = rs.getDouble("diskon_member");
                
                bayar=rs.getDouble("bayar");
                idjual = rs.getString("cnbkt");
                Double totalPerBarang = rs.getDouble("jumlah")*(rs.getDouble("harga")-(rs.getDouble("harga")*(rs.getDouble("diskon_barang")/100)));
                subTotalNoReturn = subTotalNoReturn + totalPerBarang;
            }
        } catch (SQLException ex) {
            Logger.getLogger(ReturnPenjualan.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        
    }
    
