     private void loadData(){
        sql = "select * from MCompany ";
        rs = con.queryResult(sql); 
        try {
            while(rs.next()){
                id=rs.getString("id");
                name.setText(rs.getString("name"));
            addr.setText(rs.getString("addr"));
            city.setText(rs.getString("city"));
            districts.setText(rs.getString("districts"));
            postalcode.setText(rs.getString("postalcode"));
            telp.setText(rs.getString("telp"));
            fax.setText(rs.getString("fax"));
            mail.setText(rs.getString("mail"));
            rek1_jenis.setText(rs.getString("rek1_jenis"));
            rek1_an.setText(rs.getString("rek1_an"));
            rek1_no.setText(rs.getString("rek1_no"));
            rek2_jenis.setText(rs.getString("rek2_jenis"));
            rek2_an.setText(rs.getString("rek2_an"));
            rek2_no.setText(rs.getString("rek2_no"));
            ket_inv.setText(rs.getString("ket_inv"));

            }
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    } 
    private void update(){
        HashMap<String,String> listObj = new HashMap<String,String>();       
        listObj.put("name",name.getText());
        listObj.put("addr",addr.getText());
        listObj.put("city",city.getText());
        listObj.put("districts",districts.getText());
        listObj.put("postalcode",postalcode.getText());
        listObj.put("telp",telp.getText());
        listObj.put("fax",fax.getText());
        listObj.put("mail",mail.getText());
        listObj.put("rek1_jenis",rek1_jenis.getText());
        listObj.put("rek1_an",rek1_an.getText());
        listObj.put("rek1_no",rek1_no.getText());
        listObj.put("rek2_jenis",rek2_jenis.getText());
        listObj.put("rek2_an",rek2_an.getText());
        listObj.put("rek2_no",rek2_no.getText());
        listObj.put("ket_inv",ket_inv.getText());
        if(id == null || id.trim().isEmpty() || id.equals("0")){
            sql=con.insertValue("mcompany", listObj);
            if(con.queryUpdate(sql)>0){
                JOptionPane.showMessageDialog(this,"Data Berhasil Di Simpan.", "Info", JOptionPane.INFORMATION_MESSAGE);
                loadData();
            } else {
                JOptionPane.showMessageDialog(this,"Gagal Menyimpan.", "Save", JOptionPane.ERROR_MESSAGE);
            }
            return;
        }
        sql=con.updateValue("mcompany", listObj);
        sql+="  where id = '"+id+"' ";
        if(con.queryUpdate(sql)>0){
            JOptionPane.showMessageDialog(this,"Data Berhasil Di Edit.", "Info", JOptionPane.INFORMATION_MESSAGE);
         
        } else {
            JOptionPane.showMessageDialog(this,"Gagal Menyimpan.", "Save", JOptionPane.ERROR_MESSAGE);
            
        }
    } 
