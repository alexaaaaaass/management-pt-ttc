    private Boolean test_connection(){
        Boolean status = false;
        try {
            status = con.connectDB(TServer.getText(),Integer.valueOf(TPort.getText().toString()),TDB.getText(),TUser.getText(),TPass.getText());
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(SettingConnection.class.getName()).log(Level.SEVERE, null, ex);
        }
        return status;
    }
    private int save_setting(){
        if(TServer.getText().isEmpty()){
            TInfo.setText("Server Harus Diisi!");
            TServer.requestFocus();
            return 1;
        }else if(TPort.getText().isEmpty()){
            TInfo.setText("Port Harus Diisi!");
            TPort.requestFocus();
            return 1;
        }else if(TDB.getText().isEmpty()){
            TInfo.setText("Database Harus Diisi!");
            TDB.requestFocus();
            return 1;
        }else if(TUser.getText().isEmpty()){
            TInfo.setText("User");
            TUser.requestFocus();
            return 1;
        }
        
        File sdcard = new File("setting");   
        lokasiFile = sdcard.getAbsolutePath() + File.separator + "access.txt";
     
        
        try{
            File r = new File(lokasiFile);
            FileWriter pw = new FileWriter(r);
            PrintWriter pr = new PrintWriter(pw);
            rfa.encrypt_rfa(4, "RF4<>"+TServer.getText());
            pr.println(rfa.encrypt_rfa(2,"RF4<>"+TServer.getText()));
            pr.println(rfa.encrypt_rfa(2,"RF4<>"+TPort.getText()));
            pr.println(rfa.encrypt_rfa(2,"RF4<>"+TDB.getText()));
            pr.println(rfa.encrypt_rfa(2,"RF4<>"+TUser.getText()));
            pr.println(rfa.encrypt_rfa(2,"RF4<>"+TPass.getText()));
            pw.close();
            return 0;
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, e, "Setting Server Tidak Dapat Disimpan", JOptionPane.ERROR_MESSAGE);
            return 1;
        }
    }
    private void loadSetting(){
        File sdcard = new File("setting");   
        lokasiFile = sdcard.getAbsolutePath() + File.separator + "access.txt";
        
        int a=0;
        File ft=new File(lokasiFile);
        Scanner in=null;
        
        String[] server = {
            "","","","","","",""
        };
        
        try {
            in = new Scanner(ft);
        } catch (FileNotFoundException ex) {
            //JOptionPane.showMessageDialog(this, ex, "Server Tidak Ditemukan", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        Vector<String> vt=new Vector<String>();
        while(in.hasNextLine())
        {
            server[a]=rfa.decrypt_rfa(2, in.nextLine());
            
//            vt.clear();
            a++;
        }
        
        TServer.setText(server[0].replace("RF4<>", ""));
        TPort.setText(server[1].replace("RF4<>", ""));
        TDB.setText(server[2].replace("RF4<>", ""));
        TUser.setText(server[3].replace("RF4<>", ""));
        TPass.setText(server[4].replace("RF4<>", ""));
    }
    
