    private  void listData(){
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.getDataVector().removeAllElements();
        jTable1.removeAll();
        
        sql = "select * from MDefault";
        
        rs = con.queryResult(sql);
        try {
            while(rs.next()){
                model.addRow(new Object[]{
                    rs.getString("code"),
                    rs.getString("cket"),
                    rs.getString("default_name"),
                });
            }
        } catch (SQLException ex) {
            Logger.getLogger(DefaultProgram.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
    public static void loadDeff(){
        String sql = "select * from MDefault";
        deffProgram.clear();
        ResultSet rs = ConnectDB.queryResult(sql);
        try {
            while(rs.next()){
                deffProgram.put(rs.getString("code"), rs.getString("default_name"));
            }
        } catch (SQLException ex) {
            Logger.getLogger(DefaultProgram.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        if(!niklogin.equalsIgnoreCase("")) {
            sql="select * From mkaryawan where nik = '"+Login.niklogin+"'";
            rs=ConnectDB.queryResult(sql);
            try {
                while(rs.next()){
                    deffProgram.put("ccode", rs.getString("ccode"));
                }
            } catch (SQLException ex) {
                Logger.getLogger(DefaultProgram.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
        
        sql = "select * from MCompany";
        rs = ConnectDB.queryResult(sql);
        try {
            while(rs.next()){
                deffProgram.put("pt", rs.getString("name"));
                deffProgram.put("alamat", rs.getString("addr"));
                deffProgram.put("telp", rs.getString("telp"));
                deffProgram.put("mail", rs.getString("mail"));
            }
        } catch (SQLException ex) {
            Logger.getLogger(DefaultProgram.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

