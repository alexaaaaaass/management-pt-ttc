    private void changee(){
        if(tpasslama.getText().equals("")) {
            JOptionPane.showMessageDialog(this,"Password Lama Belum di isi", "Info", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if(tpassnew.getText().equals("")) {
            JOptionPane.showMessageDialog(this,"Password Baru Belum di isi", "Info", JOptionPane.ERROR_MESSAGE);
            return;
        }
        Boolean statuss = false; 
        sql="select * from userlogin where cuser='"+tuser.getText()+"' and cpass='"+rfa.encrypt_rfa(1, tpasslama.getText())+"' ";
        rs = con.queryResult(sql);
        try {
            while(rs.next()){
                statuss = true;
            }
        } catch (SQLException ex) {
            Logger.getLogger(Login.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        if(!statuss){
            JOptionPane.showMessageDialog(this,"Password Lama salah", "Info", JOptionPane.ERROR_MESSAGE);
        } else {
            HashMap<String,String> listObj = new HashMap<String,String>();        
            listObj.put("cpass",rfa.encrypt_rfa(1, tpassnew.getText()));
            sql=con.updateValue("UserLogin", listObj);
                sql+=" where id = "+Login.idd;
            if(con.queryUpdate(sql)>0){
                status = true;
                JOptionPane.showMessageDialog(this,"Password Bergasil di ganti", "Info", JOptionPane.INFORMATION_MESSAGE);
                
                dispose();
            }
            
        }
    }
    
