    private function resolveCoaClass(string $code, string $name, string $defaultCode): int
    {
        try {
            if (Schema::hasTable('coa_classes')) {
                $class = CoaClass::where('code', $code)
                    ->orWhere('code', $defaultCode)
                    ->orWhere('name', 'LIKE', "%{$name}%")
                    ->first();

                if ($class) {
                    return $class->id;
                }

                $created = CoaClass::create([
                    'karyawan_id' => 1,
                    'code' => $defaultCode,
                    'name' => $name,
                    'status' => 'aktif',
                ]);

                return $created->id;
            }
        } catch (\Throwable $e) {}

        return 1;
    }
